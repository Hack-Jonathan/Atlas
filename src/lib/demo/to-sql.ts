/**
 * Renders a generated history as plain SQL (seed 03). Times are written relative
 * to `now()`, so the demo always looks recent whenever the seed is applied.
 */
import type { GeneratedHistory, TimeRef } from "@/lib/demo/history";

export interface SqlContext {
  missionId: string;
  astronautId: string;
  surgeonId: string;
}

/** SQL expression for a relative time. */
export function timeSql(t: TimeRef): string {
  if (t.kind === "now") {
    return t.secondsAgo === 0 ? "now()" : `now() - interval '${t.secondsAgo} seconds'`;
  }
  return `date_trunc('day', now()) - interval '${t.daysAgo} days' + interval '${t.minute} minutes'`;
}

/** Quotes a SQL string literal (or NULL). */
function q(v: string | null): string {
  return v === null ? "null" : `'${v.replace(/'/g, "''")}'`;
}

/** Catalog ids are random per database, so history rows reference indicators by code. */
function indicatorRef(code: string): string {
  return `(select id from public.indicator where code = ${q(code)})`;
}

function num(v: number | null): string {
  return v === null ? "null" : String(v);
}

function insert(table: string, columns: string[], rows: string[][]): string {
  if (rows.length === 0) return `-- (no ${table} rows)\n`;
  const values = rows.map((r) => `  (${r.join(", ")})`).join(",\n");
  return `insert into public.${table} (${columns.join(", ")}) values\n${values};\n`;
}

/** Full seed-03 SQL text. Deterministic for a given history. */
export function historyToSql(h: GeneratedHistory, ctx: SqlContext): string {
  const { missionId: mission, astronautId: astro, surgeonId: surgeon } = ctx;
  const parts: string[] = [];

  parts.push(
    "-- =============================================================================",
    "-- Atlas · Seed 03 · Simulated 75-day history of the demo astronaut (RF-48)",
    "-- GENERATED by `npm run db:generate-history` (scripts/generate-history.ts).",
    "-- Do not edit by hand: change src/lib/demo/history.ts and regenerate.",
    "-- Colors, deviations, reasons and alerts come from src/lib/rules (RN-04…RN-06).",
    "-- All values are simulated demonstration data (RN-15).",
    "-- =============================================================================",
    "",
  );

  parts.push(
    "-- Personal baselines from the pre-flight check-ups (RN-05)",
    insert(
      "baseline",
      ["id", "profile_id", "indicator_id", "reference_value", "std_dev", "sample_count", "source", "updated_at"],
      h.baselines.map((b) => [q(b.id), q(astro), indicatorRef(b.indicatorCode), num(b.referenceValue), num(b.stdDev), num(b.sampleCount), "'calculated'", timeSql(b.at)]),
    ),
  );

  parts.push(
    "-- Check-ups",
    insert(
      "checkup",
      ["id", "profile_id", "mission_id", "started_at", "completed_at", "status", "overall_result"],
      h.checkups.map((c) => [q(c.id), q(astro), q(mission), timeSql(c.startedAt), c.completedAt ? timeSql(c.completedAt) : "null", q(c.status), q(c.overallResult)]),
    ),
  );

  parts.push(
    "-- Measurements (manual check-up values and simulated telemetry/exams)",
    insert(
      "measurement",
      ["id", "profile_id", "mission_id", "indicator_id", "checkup_id", "numeric_value", "measured_at", "mission_phase", "origin", "traffic_light", "deviation_pct", "status_reason"],
      h.measurements.map((m) => [q(m.id), q(astro), q(mission), indicatorRef(m.indicatorCode), q(m.checkupId), num(m.value), timeSql(m.at), q(m.phase), q(m.origin), q(m.trafficLight), num(m.deviationPct), q(m.reason)]),
    ),
  );

  parts.push(
    "-- Alerts from the rules engine (value and trend)",
    insert(
      "alert",
      ["id", "profile_id", "indicator_id", "measurement_id", "type", "level", "message", "status", "created_at", "attended_at"],
      h.alerts.map((a) => [q(a.id), q(astro), indicatorRef(a.indicatorCode), q(a.measurementId), q(a.type), q(a.level), q(a.message), q(a.status), timeSql(a.at), a.attendedAt ? timeSql(a.attendedAt) : "null"]),
    ),
  );

  // Messages: arrives_at is computed by the message_set_arrival trigger (RN-09).
  // read_at is set relative to sent_at so it is always after arrival.
  const messageRows = h.messages.map((m) => {
    const sent = timeSql(m.sentAt);
    return [
      q(m.id), q(mission), q(m.fromAstronaut ? astro : surgeon), q(m.fromAstronaut ? surgeon : astro),
      q(m.type), q(m.priority), q(m.subject), q(m.body), q(m.checkupId), q(m.alertId), q(m.replyToId),
      sent, m.read ? `${sent} + interval '1 hour'` : "null",
    ];
  });
  parts.push(
    "-- Ship–ground messages (arrival time computed by trigger, RN-09)",
    insert(
      "message",
      ["id", "mission_id", "sender_id", "recipient_id", "type", "priority", "subject", "body", "checkup_id", "alert_id", "reply_to_id", "sent_at", "read_at"],
      messageRows,
    ),
  );

  return parts.join("\n");
}
